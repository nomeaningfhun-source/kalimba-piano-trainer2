let LANG = (() => {
  try { const v = JSON.parse(localStorage.getItem('kt.lang')); if (v === 'th' || v === 'en') return v; } catch (e) { /* none saved */ }
  return /^th\b/i.test(navigator.language || '') ? 'th' : 'en';
})();

function t(key, vars) {
  let s = (I18N[LANG] && I18N[LANG][key]) || I18N.th[key] || key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] != null ? vars[k] : m));
  return s;
}

function applyI18n(root) {
  root = root || document;
  root.querySelectorAll('[data-i18n]').forEach(e => { e.textContent = t(e.dataset.i18n); });
  root.querySelectorAll('[data-i18n-ph]').forEach(e => { e.placeholder = t(e.dataset.i18nPh); });
  root.querySelectorAll('[data-i18n-aria]').forEach(e => { e.setAttribute('aria-label', t(e.dataset.i18nAria)); });
  document.documentElement.lang = LANG;
  document.title = t('app.title');
}
